class Log:
    def __init__(self):
        self.lines = []

    def info(self, msg, *a):
        self.lines.append(msg % a)

    warning = error = info


class FakeSite:
    """記下送出的請求。post_result 是 None 就當成功，並讓下一次 state 出現新的提交。"""

    def __init__(self, state, current_rows=None, post_error=None, echo=True):
        self.states = [state]
        self.current_rows = current_rows
        self.post_error = post_error
        self.echo = echo
        self.posts = []
        self.downloads = []

    def state(self):
        return copy.deepcopy(self.states[-1])

    def download(self, sid):
        self.downloads.append(sid)
        return self.current_rows

    def post_submission(self, body):
        self.posts.append(body)
        if self.post_error:
            raise self.post_error
        new = copy.deepcopy(self.states[-1])
        key = site_api.submission_key(body["phase"], body.get("tradingDate"))
        new["mySubmissions"] = [s for s in new.get("mySubmissions", []) if s["tradingDate"] != key] + [
            {"id": "new-1", "phase": body["phase"], "tradingDate": key, "fileName": body["fileName"],
             "submittedAt": "2026-11-08T23:31:00.000Z", "score": None, "isAutoGenerated": 0}]
        self.states.append(new)
        if self.echo:
            self.current_rows = self.sent_rows(body)
        return {"success": True}

    @staticmethod
    def sent_rows(body):
        p = body["payload"]
        if body["phase"] == 1:
            return [["id"] + p["dates"]] + [[s] + [str(v) for v in r] for s, r in zip(p["stockIds"], p["predictions"])]
        return [["id", body["tradingDate"]]] + [[s, str(v)] for s, v in zip(p["stockIds"], p["predictions"])]


def state(phase2=True, submissions=(), team_count=0):
    return {"config": {"phase1OpenAt": "2026-09-16T00:00:00.000Z", "phase1Deadline": "2026-12-24T15:59:00.000Z"},
            "phase2Days": [{"tradingDate": T, "enabled": 1, "openAt": "2026-11-08 07:00:00",
                            "deadline": "2026-11-09 01:00:00"}] if phase2 else [],
            "uploadQuota": {"phase1": {"userLimit": 0, "teamLimit": 10, "userCount": 0, "teamCount": team_count},
                            "phase2ByDate": {T: {"userLimit": 0, "teamLimit": 10, "userCount": 0,
                                                 "teamCount": team_count}}},
            "mySubmissions": list(submissions)}


