def write_csv(tmp_path, phase, values=1):
    header = ["id"] + DATES if phase == 1 else ["id", T]
    vals = {(d, s): values for d in header[1:] for s in IDS}
    rows = submit.build_rows(phase, header, IDS, vals)
    path = tmp_path / "data" / "submission" / ("p1.csv" if phase == 1 else f"submission_{T}.csv")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(submit.rows_to_bytes(rows))
    return path, rows


def statuses(cfg):
    return [json.loads(x)["status"] for x in submit.log_path(cfg).read_text().splitlines()]


