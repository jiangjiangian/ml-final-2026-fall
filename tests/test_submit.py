def test_already_submitted_rules():
    p1_today = {"phase": 1, "tradingDate": "phase1", "submittedAt": "2026-11-08T23:15:00.000Z", "isAutoGenerated": 0}
    p1_old = dict(p1_today, submittedAt="2026-11-06T10:34:55.080Z")
    forced = {"phase": 2, "tradingDate": T, "submittedAt": "2026-11-09 00:59:00", "isAutoGenerated": 1}
    ours = dict(forced, isAutoGenerated=0)
    assert run_daily_test.already_submitted(state(submissions=[p1_today]), 1, "2026-11-09", "2026-11-09")
    assert run_daily_test.already_submitted(state(submissions=[p1_old]), 1, "2026-11-09", "2026-11-09") is None
    assert run_daily_test.already_submitted(state(submissions=[forced]), 2, T, T) is None
    assert run_daily_test.already_submitted(state(submissions=[ours]), 2, T, T)


def add_log(cfg, status, run_id, phase=2, key=T, day=T, runner="x"):
    submit.log_path(cfg).parent.mkdir(parents=True, exist_ok=True)
    with open(submit.log_path(cfg), "a") as f:
        f.write(json.dumps({"time": f"{day}T07:12:00+08:00", "phase": phase, "trading_date": key, "status": status,
                            "runner": runner, "run_id": run_id, "file": "f"}) + "\n")


def test_open_prepared_pairs_by_run_id(env):
    assert submit.open_prepared(env, 2, T, T) is None
    for status in ("prepared", "post_failed", "not_received"):
        add_log(env, status, "a")
    assert submit.open_prepared(env, 2, T, T)["run_id"] == "a"          # POST 失敗後不自動重送
    add_log(env, "done", "a")
    assert submit.open_prepared(env, 2, T, T) is None
    add_log(env, "not_sent", "b")                                        # union 合併後 b 的結果排在前面
    add_log(env, "prepared", "b")
    assert submit.open_prepared(env, 2, T, T) is None
    add_log(env, "prepared", "c")
    assert submit.open_prepared(env, 2, T, T, exclude_run="c") is None
    assert submit.open_prepared(env, 2, T, T)["run_id"] == "c"
    add_log(env, "prepared", "d", phase=1, key="phase1", day="2026-11-08")
    assert submit.open_prepared(env, 1, "phase1", "2026-11-09") is None   # 別天的不算


