def test_backup_download_failure_does_not_block(env, tmp_path):
    path, _ = write_csv(tmp_path, 2)
    cur = {"id": "c", "phase": 2, "tradingDate": T, "submittedAt": "2026-11-08 23:00:00", "isAutoGenerated": 0}
    site = FakeSite(state(submissions=[cur]))
    real_download = site.download
    calls = []

    def flaky(sid):
        calls.append(sid)
        if len(calls) == 1:
            raise crawler.TransientError("下載中斷")
        return real_download(sid)

    site.download = flaky
    assert submit.run(env, site, 2, path, T, Log(), clock=lambda: NOW) == "done"
    assert len(site.posts) == 1


