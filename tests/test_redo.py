class Site:
    """假網站：送出的檔變成網站上目前那份（id new-1、new-2…），下載回來和送出的一樣。
    add() 也用來模擬組員手動交。used 是今天已經用掉的上傳次數（加上 POST 的次數）。"""

    def __init__(self):
        self.submissions, self.files, self.posts, self.used = [], {}, [], 0
        self.calls, self.fail_on, self.post_error = 0, None, None   # fail_on：第幾次讀 state 時連不上

    def add(self, sid, rows):
        minute = len(self.submissions) + 1   # 越後面交的 submittedAt 越晚，current_entry 取最晚的
        self.submissions.append({"id": sid, "phase": 2, "tradingDate": T, "fileName": f"{sid}.csv",
                                 "submittedAt": f"2026-11-12T23:{minute:02d}:00.000Z", "score": None,
                                 "isAutoGenerated": 0})
        self.files[sid] = rows

    def state(self):
        self.calls += 1
        if self.calls == self.fail_on:
            raise ConnectionError("網站連不上")
        count = self.used + len(self.posts)
        return {"phase2Days": [{"tradingDate": T, "enabled": 1, "openAt": "2026-11-12 01:01:00",
                                "deadline": "2026-11-13 01:00:00"}],
                "uploadQuota": {"phase2ByDate": {T: {"userLimit": 0, "teamLimit": 10, "userCount": 0,
                                                     "teamCount": count}}},
                "mySubmissions": copy.deepcopy(self.submissions)}

    def download(self, sid):
        return copy.deepcopy(self.files[sid])

    def post_submission(self, body):
        self.posts.append(body)
        if self.post_error:
            raise self.post_error
        p = body["payload"]
        self.add(f"new-{len(self.posts)}", [["id", T]] + [[s, str(v)] for s, v in zip(p["stockIds"], p["predictions"])])
        return {"success": True}

    def close(self):
        pass


