def test_completeness_follows_the_two_definitions():
    cfg = {"daily_model": {"kind": "c2v2d"}}
    assert tp.completeness(cfg, "c2v2d", pred(FIRST)) == (True, [], 0)
    assert tp.completeness(cfg, "c2v2d", pred(FIRST, missing=1)) == (False, ["方向模型的狀態缺 1 個"], 1)
    ok, reasons, missing = tp.completeness(cfg, FALLBACK, pred(FIRST, missing=2))
    assert not ok and reasons == [f"用了備援 {FALLBACK}", "方向模型的狀態缺 2 個"] and missing == 2
    no_column = pred(FIRST).drop(columns="missing_states")   # rank_ensemble、persist 沒有這欄
    assert tp.completeness({"daily_model": {"kind": "rank_ensemble"}}, "rank_ensemble", no_column) == (True, [], None)


