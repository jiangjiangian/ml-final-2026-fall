def test_push_failure_before_post_means_no_upload(env, tmp_path):
    path, _ = write_csv(tmp_path, 2)
    site = FakeSite(state())
    with pytest.raises(RuntimeError):
        submit.run(env, site, 2, path, T, Log(), before_post=lambda: False, now=NOW)
    assert site.posts == [] and statuses(env) == ["prepared", "not_sent"]


def test_post_failure_is_not_retried(env, tmp_path):
    path, _ = write_csv(tmp_path, 2)
    site = FakeSite(state(), post_error=crawler.TransientError("上傳：連線失敗"))
    with pytest.raises(crawler.TransientError):
        submit.run(env, site, 2, path, T, Log(), now=NOW)
    assert len(site.posts) == 1 and statuses(env) == ["prepared", "post_failed", "not_received"]


def test_mismatch_after_upload_is_an_error(env, tmp_path):
    path, _ = write_csv(tmp_path, 2)
