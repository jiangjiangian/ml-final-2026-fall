def test_already_submitted_rules():
    p1_today = {"phase": 1, "tradingDate": "phase1", "submittedAt": "2026-11-08T23:15:00.000Z", "isAutoGenerated": 0}
    p1_old = dict(p1_today, submittedAt="2026-11-06T10:34:55.080Z")
    forced = {"phase": 2, "tradingDate": T, "submittedAt": "2026-11-09 00:59:00", "isAutoGenerated": 1}
    ours = dict(forced, isAutoGenerated=0)
    assert run_daily_test.already_submitted(state(submissions=[p1_today]), 1, "2026-11-09", "2026-11-09")
    assert run_daily_test.already_submitted(state(submissions=[p1_old]), 1, "2026-11-09", "2026-11-09") is None
    assert run_daily_test.already_submitted(state(submissions=[forced]), 2, T, T) is None
    assert run_daily_test.already_submitted(state(submissions=[ours]), 2, T, T)


def test_unfinished_upload_blocks_until_done(env):
    def add(status, phase=2, key=T, day=T):
        submit.log_path(env).parent.mkdir(parents=True, exist_ok=True)
        with open(submit.log_path(env), "a") as f:
            f.write(json.dumps({"time": f"{day}T07:12:00+08:00", "phase": phase, "trading_date": key,
                                "status": status, "runner": "x", "file": "f"}) + "\n")

    assert run_daily_test.unfinished_upload(env, 2, T, T) is None
    add("prepared")
    add("post_failed")
    add("not_received")
    assert run_daily_test.unfinished_upload(env, 2, T, T) is not None   # POST 失敗後不自動重送
    add("done")
    assert run_daily_test.unfinished_upload(env, 2, T, T) is None
    add("prepared", phase=1, key="phase1", day="2026-11-08")
    assert run_daily_test.unfinished_upload(env, 1, "phase1", "2026-11-09") is None   # 別天的不算
    add("prepared")
    add("not_sent")
    assert run_daily_test.unfinished_upload(env, 2, T, T) is None


