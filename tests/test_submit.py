def test_dry_run_does_not_post(env, tmp_path):
    env["submit"]["enabled"] = False
    path, _ = write_csv(tmp_path, 2)
    site = FakeSite(state())
    assert submit.run(env, site, 2, path, T, Log(), clock=lambda: NOW) == "dry_run"
    assert site.posts == [] and statuses(env) == ["dry_run"]


def test_upload_posts_once_and_verifies(env, tmp_path):
    path, rows = write_csv(tmp_path, 2)
    site = FakeSite(state())
    calls = []
    assert submit.run(env, site, 2, path, T, Log(), before_post=lambda: calls.append(1) or True, clock=lambda: NOW) == "done"
    assert len(site.posts) == 1 and calls == [1]
    body = site.posts[0]
    assert body["phase"] == 2 and body["tradingDate"] == T and body["payload"]["predictions"] == [1, 1, 1]
    assert statuses(env) == ["prepared", "done"]


def test_phase1_body_has_no_trading_date_and_backs_up_current(env, tmp_path):
    path, rows = write_csv(tmp_path, 1)
    old = {"id": "old", "phase": 1, "tradingDate": "phase1", "submittedAt": "2026-11-06T10:34:55.080Z",
           "score": 0.0027, "isAutoGenerated": 0}
    old_rows = [["id"] + DATES] + [[s, "0", "0", "0"] for s in IDS]
