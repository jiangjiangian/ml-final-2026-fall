def record(folder):
    return json.loads((folder / f"complete_{T}.json").read_text(encoding="utf-8"))


def submitted(folder, name=f"submission_{T}.csv"):
    return submit.read_rows(folder / name)


def statuses(cfg):
    return [json.loads(x)["status"] for x in submit.log_path(cfg).read_text().splitlines()]


